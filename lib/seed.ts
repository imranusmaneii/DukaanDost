function daysAgo(days: number, hour: number, minute: number): string {
  const d = new Date();
  d.setDate(d.getDate() - days);
  d.setHours(hour, minute, 0, 0);
  return d.toISOString();
}

function buildOrder(
  orderNumber: number,
  customerName: string,
  customerPhone: string,
  address: string,
  lines: Array<[string, number]>,
  paymentMethod: PaymentMethod,
  paymentStatus: PaymentStatus,
  orderStatus: OrderStatus,
  days: number,
  hour: number,
  minute: number,
  note?: string,
): Order {
  const items = lines.map(([productId, qty]) => {
    const product = seedProducts.find((p) => p.id === productId)!;
    return {
      productId,
      name: product.name,
      price: product.price,
      qty,
      emoji: product.emoji,
      theme: product.theme,
    };
  });
  return {
    id: `o${orderNumber}`,
    orderNumber,
    customerName,
    customerPhone,
    address,
    items,
    total: items.reduce((sum, item) => sum + item.price * item.qty, 0),
    paymentMethod,
    paymentStatus,
    orderStatus,
    note,
    createdAt: daysAgo(days, hour, minute),
  };
}

